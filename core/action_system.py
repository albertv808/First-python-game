class ActionSystem:

    def start_activation(self, piece):
        """Prepara les accions de la peça."""

    def get_available_actions(self, piece):
        """Retorna les accions que pot executar ara."""

    def execute_action(self, piece, action):
        """Valida i consumeix una acció."""

    def finish_activation(self, piece):
        """Marca la peça com a activació finalitzada."""